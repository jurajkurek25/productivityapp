export interface TaskCompletionRecord {
  date: ISODate;
  scheduledCount: number;
  completedCount: number;
  missedCount: number;
  scheduledMinutes: number;
  completedMinutes: number;
}

export type EnergyTrend = "rising" | "falling" | "stable";

export interface EnergyState {
  date: ISODate;
  /** 0 (depleted) .. 100 (fully fresh) */
  score: number;
  trend: EnergyTrend;
  /** Multiplier applied to the day's base capacity, e.g. 0.6 .. 1.15 */
  loadMultiplier: number;
  signals: {
    completionRate7d: number;
    completionRate14d: number;
    missedStreak: number;
    completedStreak: number;
    overdueLoad: number;
  };
}

export interface DomainBalanceEntry {
  domain: LifeDomain;
  scheduledMinutes: number;
  completedMinutes: number;
  completionRate: number;
  shareOfTotal: number;
  neglected: boolean;
}

export interface PriorityReport {
  windowStart: ISODate;
  windowEnd: ISODate;
  domains: DomainBalanceEntry[];
  neglectedDomains: LifeDomain[];
}

export interface StudyMaterialItem {
  id: string;
  title: string;
  estimatedMinutes: number;
  /** 1 (easy) .. 5 (hard). Harder topics get scheduled earlier and reviewed more. */
  difficulty: number;
}

export interface StudyPlanDay {
  date: ISODate;
  items: { materialId: string; title: string; minutes: number; isReview: boolean }[];
  totalMinutes: number;
}

export interface StudyPlan {
  goalId: string;
  examDate: ISODate;
  days: StudyPlanDay[];
}
